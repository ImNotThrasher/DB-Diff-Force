package studio.dbdiff;

import org.flywaydb.core.api.MigrationVersion;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Builds a reviewable Flyway migration from a reconstructed schema to a live database schema. */
final class FlywayMigrationGenerator {
    private static final Pattern VERSIONED_FILE = Pattern.compile("(?i)^V(\\d+(?:[._]\\d+)*)__.*\\.sql$");
    private static final Pattern VERSION = Pattern.compile("\\d+(?:\\.\\d+)*");
    private static final Pattern DESCRIPTION = Pattern.compile("[A-Za-z0-9_]+");

    private FlywayMigrationGenerator() { }

    static String generate(List<DiffEngine.Result> results, String database, DatabaseEngine engine,
                           Map<SchemaObject.Key, Set<SchemaObject.Key>> oldDependencies,
                           Map<SchemaObject.Key, Set<SchemaObject.Key>> currentDependencies) {
        List<DiffEngine.Result> reversed = new ArrayList<>(results.size());
        for (DiffEngine.Result result : results) {
            DiffEngine.Status status = switch (result.status()) {
                case SOURCE_ONLY -> DiffEngine.Status.TARGET_ONLY;
                case TARGET_ONLY -> DiffEngine.Status.SOURCE_ONLY;
                default -> result.status();
            };
            reversed.add(new DiffEngine.Result(result.key(), status, result.target(), result.source(), result.diffLines()));
        }
        List<DiffEngine.Result> ordered = SqlExporter.orderByDependencies(reversed,
                EnumSet.of(DiffEngine.Status.SOURCE_ONLY, DiffEngine.Status.TARGET_ONLY, DiffEngine.Status.CHANGED),
                currentDependencies, oldDependencies);

        StringBuilder sql = new StringBuilder("-- Flyway migration generated by " + AppInfo.NAME + "\n"
                + "-- Direction: reconstructed Flyway schema -> current database schema (" + database + ").\n"
                + "-- Review and test this migration before use. It was not executed.\n"
                + "-- Object removals and potentially destructive or unsupported changes are comments for manual review.\n\n");
        for (DiffEngine.Result result : ordered) {
            if (result.status() == DiffEngine.Status.IDENTICAL) continue;
            SchemaObject object = result.source() != null ? result.source() : result.target();
            sql.append("-- ").append(object.key().kind()).append(' ').append(object.key().qualifiedName()).append('\n');
            switch (result.status()) {
                case SOURCE_ONLY -> sql.append(createObject(result.source(), engine));
                case TARGET_ONLY -> sql.append(reviewOnly("The object exists in the old Flyway schema but not in the current database; review whether it should be dropped.", object));
                case CHANGED -> sql.append(updateObject(result.source(), result.target(), database, engine));
                case IDENTICAL -> { }
            }
            sql.append('\n');
        }
        return sql.toString();
    }

    private static String createObject(SchemaObject desired, DatabaseEngine engine) {
        if (unavailable(desired)) return reviewOnly("The current database did not provide a complete definition.", desired);
        String definition = terminate(desired.definition());
        if (engine == DatabaseEngine.SQLSERVER) return definition + "\nGO\n";
        if (desired.key().kind() == SchemaObject.Kind.PROCEDURE || desired.key().kind() == SchemaObject.Kind.FUNCTION
                || desired.key().kind() == SchemaObject.Kind.TRIGGER)
            return "DELIMITER $$\n" + definition + " $$\nDELIMITER ;\n";
        return definition + "\n";
    }

    private static String updateObject(SchemaObject desired, SchemaObject old, String database, DatabaseEngine engine) {
        if (unavailable(desired) || unavailable(old))
            return reviewOnly("A complete definition is unavailable; no update statement was generated.", desired);
        if (desired.key().kind() == SchemaObject.Kind.TABLE) {
            if (engine == DatabaseEngine.SQLSERVER)
                return reviewOnly("Automatic SQL Server table migration is not supported yet.", desired);
            String alter = TableAlterGenerator.generate(desired.definition(), old.definition(), database, desired.key().name()).orElse(null);
            if (alter == null) return reviewOnly("The table difference could not be translated safely to ALTER TABLE.", desired);
            if (Pattern.compile("(?i)\\b(?:DROP|MODIFY)\\b").matcher(alter).find())
                return reviewOnly("The table change removes or modifies existing schema and needs manual review; no potentially destructive ALTER was included.", desired);
            return removeDatabaseQualifier(alter, database) + "\n";
        }
        String ddl = desired.definition().strip();
        if (engine == DatabaseEngine.SQLSERVER) {
            if (desired.key().kind() == SchemaObject.Kind.TRIGGER || desired.key().kind() == SchemaObject.Kind.VIEW
                    || desired.key().kind() == SchemaObject.Kind.PROCEDURE || desired.key().kind() == SchemaObject.Kind.FUNCTION) {
                ddl = ddl.replaceFirst("(?is)^\\s*CREATE\\s+(OR\\s+ALTER\\s+|OR\\s+REPLACE\\s+)?", "CREATE OR ALTER ");
                return terminate(ddl) + "\nGO\n";
            }
        }
        if (desired.key().kind() == SchemaObject.Kind.VIEW) {
            ddl = ddl.replaceFirst("(?is)^\\s*CREATE\\s+(OR\\s+REPLACE\\s+)?", "CREATE OR REPLACE ");
            return terminate(ddl) + "\n";
        }
        return reviewOnly("Updating this object type requires DROP/recreate or dialect-specific handling; review manually.", desired);
    }

    private static String removeDatabaseQualifier(String alter, String database) {
        if (database == null || database.isBlank()) return alter;
        String quoted = "`" + database.replace("`", "``") + "`.";
        return alter.replace("ALTER TABLE " + quoted, "ALTER TABLE ");
    }

    private static String reviewOnly(String reason, SchemaObject object) {
        return "-- REVIEW ONLY: " + reason + "\n-- Current definition for reference:\n"
                + (object == null || object.definition().isBlank() ? "-- (definition unavailable)\n" : commentDefinition(object.definition()));
    }

    private static String commentDefinition(String definition) {
        return definition.lines().map(line -> "-- " + line).collect(java.util.stream.Collectors.joining("\n")) + "\n";
    }

    private static boolean unavailable(SchemaObject object) {
        return object == null || object.definition().isBlank()
                || object.definition().startsWith("-- " + AppInfo.NAME + ": SHOW CREATE")
                || object.definition().startsWith("-- " + AppInfo.NAME + ": SQL Server");
    }

    private static String terminate(String definition) {
        String text = definition.stripTrailing();
        return text.endsWith(";") ? text : text + ";";
    }

    static String nextVersion(Path folder) throws IOException {
        if (!Files.isDirectory(folder)) throw new IOException("La carpeta Flyway no existe o no es válida.");
        MigrationVersion latest = null;
        try (var paths = Files.walk(folder)) {
            for (Path path : paths.filter(Files::isRegularFile).toList()) {
                Matcher matcher = VERSIONED_FILE.matcher(path.getFileName().toString());
                if (!matcher.matches()) continue;
                MigrationVersion found = MigrationVersion.fromVersion(matcher.group(1).replace('_', '.'));
                if (latest == null || found.compareTo(latest) > 0) latest = found;
            }
        }
        if (latest == null) return "1";
        String[] parts = latest.getVersion().split("\\.");
        java.math.BigInteger last = new java.math.BigInteger(parts[parts.length - 1]).add(java.math.BigInteger.ONE);
        parts[parts.length - 1] = last.toString();
        return String.join(".", parts);
    }

    static String fileName(String version, String description) {
        if (version == null || !VERSION.matcher(version).matches()) throw new IllegalArgumentException("La versión debe contener números separados por puntos.");
        if (description == null || !DESCRIPTION.matcher(description).matches()) throw new IllegalArgumentException("La descripción solo puede contener letras, números y guion bajo.");
        return "V" + version + "__" + description + ".sql";
    }

    static Path save(Path folder, String version, String description, String sql) throws IOException {
        if (!Files.isDirectory(folder)) throw new IOException("La carpeta Flyway no existe o no es válida.");
        MigrationVersion requested;
        try { requested = MigrationVersion.fromVersion(version); }
        catch (RuntimeException ex) { throw new IOException("La versión Flyway no es válida.", ex); }
        if (!VERSION.matcher(version).matches()) throw new IOException("La versión Flyway no es válida.");
        if (!DESCRIPTION.matcher(description == null ? "" : description).matches()) throw new IOException("La descripción solo puede contener letras, números y guion bajo.");
        try (var paths = Files.walk(folder)) {
            boolean collision = paths.filter(Files::isRegularFile).map(path -> VERSIONED_FILE.matcher(path.getFileName().toString()))
                    .filter(Matcher::matches)
                    .anyMatch(matcher -> MigrationVersion.fromVersion(matcher.group(1).replace('_', '.')).compareTo(requested) == 0);
            if (collision) throw new IOException("Ya existe una migración Flyway con la versión " + version + ".");
        }
        Path file = folder.resolve(fileName(version, description));
        try {
            return Files.writeString(file, sql, StandardCharsets.UTF_8, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
        } catch (java.nio.file.FileAlreadyExistsException ex) {
            throw new IOException("El archivo de migración ya existe: " + file.getFileName(), ex);
        }
    }
}
